const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  const check = (name, value) => { assert.ok(value, name); checks.push(name); };
  const data = () => page.evaluate(() => JSON.parse(localStorage.getItem('wanglemai-prototype-v1')));
  const action = (name, scope = page) => scope.locator(`[data-action="${name}"]`);
  const scene = name => page.locator(`[data-scene="${name}"]`).click();
  const url = pathToFileURL(path.resolve('prototype/index.html')).href;
  fs.mkdirSync('test-results', { recursive: true });
  try {
    await page.goto(url);
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    check('initial two independent widgets', await page.locator('.widget').count() === 2);
    check('seed has eight records', (await data()).items.length === 8);
    await page.screenshot({ path: 'docs/prototype-desktop.png', fullPage: true });

    const second = page.locator('[data-widget="102"]');
    await action('create', second).click();
    check('widget inherits shopping list', await page.locator('[name=listId]').inputValue() === 'list-shopping-default');
    await page.locator('#editor-form [type=submit]').click();
    check('empty title rejected', (await page.locator('#form-error').textContent()).includes('先写点'));
    await page.locator('[name=title]').fill('咖啡豆');
    await page.locator('[name=quantityDecimal]').fill('-3');
    await page.locator('#editor-form [type=submit]').click();
    check('invalid quantity rejected without mutation', (await data()).items.length === 8 && (await page.locator('#form-error').textContent()).includes('数量需为'));
    await page.locator('[name=quantityDecimal]').fill('3');
    await page.locator('[name=unit]').fill('袋');
    await page.locator('[name=pinned]').check();
    await page.screenshot({ path: 'docs/prototype-editor.png', fullPage: true });
    await page.locator('#editor-form [type=submit]').click();
    check('save closes editor and persists record', await page.locator('#editor-form').count() === 0 && (await data()).items.some(x => x.title === '咖啡豆'));
    const coffeeId = (await data()).items.find(x => x.title === '咖啡豆').id;
    await second.locator(`[data-action=complete][data-id="${coffeeId}"]`).click();
    check('widget completion persisted', (await data()).items.find(x => x.id === coffeeId).completed);
    await action('undo-widget', second).click();
    check('widget undo restores item', !(await data()).items.find(x => x.id === coffeeId).completed);

    await scene('config');
    await page.locator('#config-list').selectOption('list-shopping-default');
    await action('save-config').click();
    check('independent configuration can bind same list', (await data()).widgets.every(x => x.listId === 'list-shopping-default'));
    await page.locator('[data-widget="101"] [data-action=edit]').filter({ hasText: '咖啡豆' }).click();
    await page.locator('[name=title]').fill('手冲咖啡豆');
    await page.locator('#editor-form [type=submit]').click();
    check('both widgets refresh after edit', await page.locator('.widget [data-action=edit]').filter({ hasText: '手冲咖啡豆' }).count() === 2);

    await action('create', second).click();
    await page.locator('[name=batch]').check();
    await page.locator('[name=title]').fill('苹果\r\n\n香蕉\n鸡蛋');
    await page.locator('#editor-form [type=submit]').click();
    const afterBatch = await data();
    check('batch ignores blank lines and commits three', afterBatch.items.length === 12 && ['苹果', '香蕉', '鸡蛋'].every(t => afterBatch.items.some(x => x.title === t)));
    await action('create', second).click();
    await page.locator('[name=batch]').check();
    await page.locator('[name=title]').fill('合法标题\n' + '长'.repeat(201));
    await page.locator('#editor-form [type=submit]').click();
    check('invalid batch is atomic with original line number', (await data()).items.length === 12 && (await page.locator('#form-error').textContent()).includes('第 2 行'));
    await action('close-editor').click();
    await action('create', second).click();
    check('draft restores batch content', (await page.locator('[name=title]').inputValue()).includes('合法标题'));
    await action('discard-draft').click();
    check('discard preserves widget target list', await page.locator('[name=listId]').inputValue() === 'list-shopping-default');
    await action('close-editor').click();

    await scene('app');
    await page.locator('[data-action=kind][data-kind=SHOPPING]').click();
    await page.screenshot({ path: 'docs/prototype-app.png', fullPage: true });
    await page.locator('#search').fill('手冲');
    check('app search filters records', await page.locator('.app-row').count() === 1);
    await action('complete', page.locator('.app-row')).click();
    check('app completion has undo', await action('undo-app').count() === 1);
    await action('undo-app').click();
    check('app undo restores record', !(await data()).items.find(x => x.id === coffeeId).completed);
    await page.locator('#search').fill('%_');
    check('wildcards treated literally', await page.locator('.app-row').count() === 0);
    await action('manage').click();
    await action('new-list').click();
    await page.locator('#list-name').fill('周末采购');
    await page.locator('#name-form [type=submit]').click();
    const newListId = (await data()).lists.find(x => x.name === '周末采购').id;
    check('new list created', !!newListId);
    await action('close-modal').click();
    await action('create', page.locator('.app-bottom')).click();
    await page.locator('[name=title]').fill('周末面包');
    await page.locator('#editor-form [type=submit]').click();
    await action('manage').click();
    await page.locator(`[data-action=delete-list][data-id="${newListId}"]`).click();
    await action('dialog-yes').click();
    check('delete list migrates records', !(await data()).lists.some(x => x.id === newListId) && (await data()).items.find(x => x.title === '周末面包').listId === 'list-shopping-default');
    check('default list deletion disabled', await page.locator('[data-action=delete-list][disabled]').count() === 1);
    await action('close-modal').click();

    await action('open-settings', page.locator('.app-nav')).click();
    const downloadPromise = page.waitForEvent('download');
    await action('export').click();
    const download = await downloadPromise;
    const backupPath = path.resolve('test-results/backup.json');
    await download.saveAs(backupPath);
    const backup = JSON.parse(fs.readFileSync(backupPath, 'utf8'));
    check('backup excludes widgets and includes completed-state fields', !backup.widgets && backup.items.every(x => Object.hasOwn(x, 'completedAt')));
    const beforeImport = (await data()).items.length;
    await page.locator('#import-file').setInputFiles(backupPath);
    await action('dialog-yes').click();
    check('repeated import keeps existing IDs', (await data()).items.length === beforeImport);
    const invalid = { ...backup, schemaVersion: 999 };
    await page.locator('#import-file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) });
    await page.waitForTimeout(100);
    check('unknown backup version rejected without mutation', (await data()).items.length === beforeImport && (await page.locator('#toast').textContent()).includes('不支持'));
    const merged = structuredClone(backup);
    merged.items = [{ ...backup.items[0], id: 'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa', title: '从备份导入的记录' }];
    await page.locator('#import-file').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(merged)) });
    await action('dialog-yes').click();
    check('new backup record merges', (await data()).items.length === beforeImport + 1);
    await page.reload();
    check('browser reload preserves data', (await data()).items.some(x => x.title === '从备份导入的记录'));

    await page.locator('#theme-toggle').click();
    check('dark theme toggles', await page.locator('body').evaluate(x => x.classList.contains('dark')));
    await page.locator('#size-toggle').click();
    check('large widget renders more than three rows', await page.locator('[data-widget="101"] .widget-row').count() > 3);
    await page.setViewportSize({ width: 360, height: 900 });
    check('360px layout has no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: 'docs/prototype-mobile-dark.png', fullPage: true });
    check('no browser runtime errors', errors.length === 0);
    fs.writeFileSync('test-results/report.json', JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
    console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
